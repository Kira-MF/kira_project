STAT_VALUES = {"A": 5, "B": 4, "C": 3, "D": 2, "E": 1}

def get_obtainable_stands():
    """Get all stands that can be obtained from arrows."""
    return {name: data for name, data in STANDS.items() if data.get("obtainable", True)}

def get_stand_by_tier(tier: str) -> list:
    """Get obtainable stands of a specific tier."""
    return [name for name, data in STANDS.items()
            if data.get("tier") == tier and data.get("obtainable", True)]

def get_stands_by_part(part: int) -> list:
    return [name for name, data in STANDS.items() if data["part"] == part]

def get_random_stand(tier: str = None):
    import random
    if tier:
        pool = get_stand_by_tier(tier)
    else:
        pool = [n for n, d in STANDS.items() if d.get("obtainable", True)]
    return random.choice(pool) if pool else None

def get_weighted_random_stand():
    import random
    pool = []
    for name, data in STANDS.items():
        if not data.get("obtainable", True):
            continue
        weight = int(TIER_WEIGHTS.get(data.get("tier", "C"), 10))
        pool.extend([name] * weight)
    return random.choice(pool)

def calculate_power(stats: dict) -> int:
    return sum(STAT_VALUES.get(v, 0) for v in stats.values()) * 2

def can_evolve(stand_name: str) -> bool:
    return stand_name in EVOLUTION_CHAINS

def get_evolution(stand_name: str):
    return EVOLUTION_CHAINS.get(stand_name)

